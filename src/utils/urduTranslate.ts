export function translateNameToUrdu(englishText: string): string {
  const clean = englishText.trim();
  if (!clean) return '';
  // If already contains Arabic/Urdu Unicode script, return as-is
  if (/[\u0600-\u06FF]/.test(clean)) return clean;

  const lower = clean.toLowerCase();
  if (EXACT_PHRASE_URDU[lower]) {
    return EXACT_PHRASE_URDU[lower];
  }

  // Word-by-word translation with smart fallback
  const tokens = clean.split(/(\s+|\/|-|\(|\))/).filter((t) => t.length > 0);
  let matchedAny = false;
  const mapped = tokens.map((tok) => {
    const key = tok.toLowerCase().replace(/\.$/, '');
    if (WORD_URDU[key]) {
      matchedAny = true;
      return WORD_URDU[key];
    }
    return tok;
  });

  if (matchedAny) {
    return mapped.join('');
  }

  return clean;
}

export function translateUnitToUrdu(unitLabel: string): string {
  const clean = unitLabel.trim();
  if (!clean) return '';
  if (/[\u0600-\u06FF]/.test(clean)) return clean;
  const lower = clean.toLowerCase();
  return UNIT_URDU[lower] ?? clean;
}

export function translateStatusToUrdu(status: string): string {
  switch (status) {
    case 'Paid':
      return 'نقد / مکمل ادائیگی';
    case 'Udhaar':
      return 'ادھار';
    case 'Partial':
      return 'جزوی ادائیگی';
    case 'Quotation':
      return 'کوٹیشن / تخمینہ';
    default:
      return status;
  }
}
