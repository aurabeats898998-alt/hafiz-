function inferHexFromName(name: string): string {
  const lower = name.trim().toLowerCase();
  if (EXACT_NAME_HEX[lower]) return EXACT_NAME_HEX[lower];

  if (lower.includes('white')) return '#F3F2EC';
  if (lower.includes('cream') || lower.includes('ivory')) return '#F5ECD2';
  if (lower.includes('beige') || lower.includes('sand') || lower.includes('oat')) return '#D7C4A5';
  if (lower.includes('yellow') || lower.includes('lemon') || lower.includes('sun')) return '#EBC137';
  if (lower.includes('orange') || lower.includes('peach')) return '#EA7936';
  if (lower.includes('red') || lower.includes('tile') || lower.includes('brick')) return '#BC3B30';
  if (lower.includes('pink') || lower.includes('rose') || lower.includes('carnation')) return '#EB97AB';
  if (lower.includes('purple') || lower.includes('violet') || lower.includes('lilac') || lower.includes('mauve') || lower.includes('lavender')) return '#8B6BA8';
  if (lower.includes('blue') || lower.includes('ocean') || lower.includes('sky')) return '#3B7BB8';
  if (lower.includes('feroz') || lower.includes('teal') || lower.includes('aqua') || lower.includes('turquoise')) return '#2DA4A8';
  if (lower.includes('green') || lower.includes('lime') || lower.includes('emerald') || lower.includes('jade')) return '#4A8E59';
  if (lower.includes('brown') || lower.includes('teak') || lower.includes('coffee') || lower.includes('hazel')) return '#7C5032';
  if (lower.includes('grey') || lower.includes('silver') || lower.includes('slate') || lower.includes('ash')) return '#9CA3AF';
  if (lower.includes('black') || lower.includes('charcoal')) return '#2D3136';
  return '#CBD5E1';
}

